import { DatabaseSync } from 'node:sqlite';
import { Client } from 'pg';

const databaseUrl = process.env.DATABASE_URL;
if (!databaseUrl) throw new Error('请设置 DATABASE_URL');
const sqlitePath = process.env.SQLITE_PATH || 'server/bpms.db';
const sqlite = new DatabaseSync(sqlitePath, { readOnly: true });
const postgres = new Client({ connectionString: databaseUrl, ssl: process.env.PGSSL === 'true' ? { rejectUnauthorized: false } : undefined });

const quote = (name) => `"${String(name).replaceAll('"','""')}"`;
const withoutForeignKeys = (sql) => sql
  .replace(/INTEGER PRIMARY KEY AUTOINCREMENT/gi, 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
  .replace(/\bREAL\b/gi, 'DOUBLE PRECISION')
  .replace(/\bINTEGER\b/gi, 'BIGINT')
  .replace(/\s+REFERENCES\s+["`\[]?[\w-]+["`\]]?\s*\([^)]*\)(?:\s+ON\s+DELETE\s+(?:CASCADE|SET\s+NULL|NO\s+ACTION|RESTRICT))?/gi, '')
  .replace(/\bAUTOINCREMENT\b/gi, '');

await postgres.connect();
try {
  const tables = sqlite.prepare("SELECT name,sql FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY rowid").all();
  await postgres.query('BEGIN');
  await postgres.query('SET session_replication_role = replica');
  for (const table of [...tables].reverse()) await postgres.query(`DROP TABLE IF EXISTS ${quote(table.name)} CASCADE`);
  for (const table of tables) await postgres.query(withoutForeignKeys(table.sql));

  for (const table of tables) {
    const columns = sqlite.prepare(`PRAGMA table_info(${quote(table.name)})`).all().map((column) => column.name);
    const rows = sqlite.prepare(`SELECT * FROM ${quote(table.name)}`).all();
    if (!rows.length) continue;
    const columnSql = columns.map(quote).join(',');
    for (let offset = 0; offset < rows.length; offset += 200) {
      const batch = rows.slice(offset, offset + 200);
      const values = [];
      const tuples = batch.map((row) => `(${columns.map((column) => { values.push(row[column]); return `$${values.length}`; }).join(',')})`).join(',');
      await postgres.query(`INSERT INTO ${quote(table.name)} (${columnSql}) VALUES ${tuples}`, values);
    }
  }

  for (const table of tables) {
    const foreignKeys = sqlite.prepare(`PRAGMA foreign_key_list(${quote(table.name)})`).all();
    for (const foreignKey of foreignKeys) {
      const constraint = `fk_${table.name}_${foreignKey.from}_${foreignKey.table}`.replace(/\W/g, '_').slice(0, 60);
      await postgres.query(`ALTER TABLE ${quote(table.name)} ADD CONSTRAINT ${quote(constraint)} FOREIGN KEY (${quote(foreignKey.from)}) REFERENCES ${quote(foreignKey.table)} (${quote(foreignKey.to)}) ON DELETE ${foreignKey.on_delete || 'NO ACTION'}`);
    }
    const hasId = sqlite.prepare(`PRAGMA table_info(${quote(table.name)})`).all().some((column) => column.name === 'id' && column.pk);
    if (hasId) await postgres.query(`SELECT setval(pg_get_serial_sequence($1,'id'),GREATEST(COALESCE((SELECT MAX(id) FROM ${quote(table.name)}),0)+1,1),false)`, [table.name]);
  }
  await postgres.query('SET session_replication_role = DEFAULT');
  await postgres.query('COMMIT');

  const comparison = [];
  for (const table of tables) {
    const sqliteCount = Number(sqlite.prepare(`SELECT COUNT(*) total FROM ${quote(table.name)}`).get().total);
    const postgresCount = Number((await postgres.query(`SELECT COUNT(*) total FROM ${quote(table.name)}`)).rows[0].total);
    comparison.push({ table: table.name, sqlite: sqliteCount, postgres: postgresCount, match: sqliteCount === postgresCount });
  }
  console.table(comparison);
  if (comparison.some((item) => !item.match)) throw new Error('迁移数量校验失败');
  console.log('SQLite → PostgreSQL 数据迁移及数量校验完成');
} catch (error) {
  await postgres.query('ROLLBACK').catch(() => {});
  throw error;
} finally {
  await postgres.end();
}
