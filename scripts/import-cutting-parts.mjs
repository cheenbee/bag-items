fs.mkdirSync(backupDirectory, { recursive: true });
fs.copyFileSync(databasePath, backupPath);

const db = new DatabaseSync(databasePath);
db.exec('PRAGMA foreign_keys = ON; PRAGMA busy_timeout = 5000; BEGIN IMMEDIATE;');

const findProduct = db.prepare('SELECT id FROM product WHERE sku=?');
const countParts = db.prepare('SELECT COUNT(*) AS count FROM cutting_part WHERE product_id=?');
const insertPart = db.prepare(`
  INSERT INTO cutting_part(
    code, product_id, material_id, mold_id, name, color,
    max_length_cm, max_width_cm, quantity_per_product, type, image_url, notes
  ) VALUES (?, ?, ?, NULL, ?, '', ?, ?, ?, '导入裁片', NULL, ?)
`);

let insertedProducts = 0;
let insertedParts = 0;
const skippedProducts = [];

try {
  for (const [sku, parts] of Object.entries(productParts)) {
    const product = findProduct.get(sku);
    if (!product) {
      skippedProducts.push(`${sku}（产品不存在）`);
      continue;
    }
    if (Number(countParts.get(product.id).count) > 0) {
      skippedProducts.push(`${sku}（已有裁片）`);
      continue;
    }

    parts.forEach(([name, materialId, maxLength, maxWidth, quantity, rawSize, remark], index) => {
      const notes = [`原始裁剪尺寸：${rawSize}`, remark].filter(Boolean).join('\n');
      insertPart.run(
        `CP-${sku}-${String(index + 1).padStart(2, '0')}`,
        product.id,
        materialId,
        name,
        maxLength,
        maxWidth,
        quantity,
        notes,
      );
      insertedParts += 1;
    });
    insertedProducts += 1;
  }
  db.exec('COMMIT;');
} catch (error) {
  db.exec('ROLLBACK;');
  throw error;
} finally {
  db.close();
}

console.log(JSON.stringify({ backupPath, insertedProducts, insertedParts, skippedProducts }, null, 2));
